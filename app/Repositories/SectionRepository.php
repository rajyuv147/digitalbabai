<?php

namespace App\Repositories;

use App\Imagedetail;
use App\Models\Section;
use Illuminate\Support\Facades\Request;
use Illuminate\Support\Facades\Auth;
use App\File;
use Illuminate\Support\Facades\Storage;

class SectionRepository extends BaseRepository
{
    const Model = Section::class;

    public function create(array $data)
    {
        $data['user_id'] = Auth::user()->id;
        $data['status'] = '1';
        if($data['type'] == "File")
        {
            $data['content'] =  url('storage/'.request()->file('content')->store('Files'));
            $section = parent::create($data);
        }
        elseif($data['type'] == "Url"){
            $data['content'] = $this->convertYoutubeUrl($data['content']);
            $section =  parent::create($data);
        }elseif($data['type'] == "Content"){
            $section =  parent::create($data);
        }elseif($data['type'] == "ImageFile"){
            $data['content'] = 'multiple files';
            $section =  parent::create($data);
            foreach(request()->file('content') as $image){
                $data =  url('storage/'.$image->store('Files'));
                Imagedetail::create([
                    'section_id' => $section,
                    'file_details' => $data,
                ]);

            }
        }
        return $section;
    }

    public function update(array $data,$id)
    {
        if(request()->hasFile('content') || request()->hasFile('content')){
            if($data['type'] == "File")
            {
                $data['content'] =  url('storage/'.request()->file('content')->store('Files'));
            }
            elseif($data['type'] == "ImageFile")
            {
                $data['content'] = "multiple image";
                $getimages = Imagedetail::where('section_id',$id)->get();
                foreach($getimages as $getimage){
                    $splitimg = explode('/Files/',$getimage->file_details);
                    Storage::delete('Files'.'/'.$splitimg[1]);
                }
                Imagedetail::where('section_id',$id)->delete();
                foreach(request()->file('content') as $image){
                    $imgData =  url('storage/'.$image->store('Files'));
                    Imagedetail::create([
                        'section_id' => $id,
                        'file_details' => $imgData,
                    ]);

                }
            }
        }
        elseif($data['type'] == "Url")
        {
            Imagedetail::where('section_id',$id)->delete();
            $data['content'] = $this->convertYoutubeUrl($data['content']);
        }elseif ($data['type'] == "Content"){
            Imagedetail::where('section_id',$id)->delete();
        }

        parent::update($data,$id);
    }

    //Convert youtube url to embed code
    public function convertYoutubeUrl($url){
        $shortUrlRegex = '/youtu.be\/([a-zA-Z0-9_]+)\??/i';
        $longUrlRegex = '/youtube.com\/((?:embed)|(?:watch))((?:\?v\=)|(?:\/))(\w+)/i';

        if (preg_match($longUrlRegex, $url, $matches)) {
            $youtube_id = $matches[count($matches) - 1];
        }

        if (preg_match($shortUrlRegex, $url, $matches)) {
            $youtube_id = $matches[count($matches) - 1];
        }
        return 'https://www.youtube.com/embed/' . $youtube_id ;
    }

    public function delete($id)
    {
        $item = parent::show($id)->with('Imagedetails')->first();
        if($item->type == 'File'){
            $splitfile = explode('/Files/',$item->content);
            Storage::delete('Files'.'/'.$splitfile[1]);
        }elseif($item->type == 'ImageFile'){
            $getimages = Imagedetail::where('section_id',$id)->get();
            foreach($getimages as $getimage){
                $splitimg = explode('/Files/',$getimage->file_details);
                Storage::delete('Files'.'/'.$splitimg[1]);
            }
        }
        return parent::delete($id); // TODO: Change the autogenerated stub
    }

}